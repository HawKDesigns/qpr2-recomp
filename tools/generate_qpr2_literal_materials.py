"""Emit literal instruction bodies from the existing scalar evaluator.
No algebra is rewritten: each stage is the evaluator's original scoped body,
with instruction words/control/indices made literal. Factor values stay dynamic.
Regenerate explicitly after changing the evaluator; Windows build needs no Python.
"""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1];k=root/'third_party/xboxrecomp/src/kernel'
print('[LITERAL-GEN] reading local shape fixture', flush=True)
programs=json.loads((root/'tools/fixtures/qpr2-literal-programs.json').read_text())
print('[LITERAL-GEN] reading pixel evaluator', flush=True)
s=(k/'nv2a_gpu_pixel.inc').read_text();s=s[s.index('    GPU_REG_VARIABLE(R);',s.index('GPU_FN void gpu_rc_eval(')):]
a=s.index('    for (s = 0; s < n; s++) {');b=s.index('\n    if (rc.final0 || rc.final1) {',a)
prefix=s[:a];stage=s[a+len('    for (s = 0; s < n; s++) {'):b];assert stage.endswith('\n    }\n');stage=stage[:-len('\n    }\n')]
tail=s[b:s.index('\n}\n#endif')]
out='/* Generated by tools/generate_qpr2_literal_materials.py. */\n'
header='''#ifndef NV2A_GPU_LITERAL_PROGRAMS_H
#define NV2A_GPU_LITERAL_PROGRAMS_H
#define NV_GPU_LITERAL_CLASSES 3u
/* Captured instruction shapes only; all factor and final colors stay dynamic.
 * Unexecuted words are ignored. Unknown controls, stages or finals fall back. */
'''
for program in programs:
 cls=program['class'];n=program['control']&255;assert 0<n<=8
 out+=('#if' if cls==1 else '#elif')+f' NV_GPU_LITERAL_CLASS == {cls}\n'
 out+='GPU_FN void gpu_rc_literal(Nv2aCombiner rc,float v0[4],float v1[4],float fog[4],float t[4][4],GPU_OUT4(result))\n{\n'
 pre=prefix.replace('rc.control & 0xFF',f'{n}u').replace('rc.control >> 8',f'{program["control"]>>8}u').replace('int i;','int i;')
 pre=pre.replace('uint32_t n = '+str(n)+'u, flags = '+str(program['control']>>8)+'u, s;','uint32_t n = '+str(n)+'u, flags = '+str(program['control']>>8)+'u;')
 pre=pre.replace('(rc.stage_program & 0x1F)',f'({program["stages"]}u & 0x1F)')
 out+=pre
 for j in range(n):
  body=stage
  for key,word in [('color_icw','rgb_in'),('alpha_icw','alpha_in'),('color_ocw','rgb_out'),('alpha_ocw','alpha_out')]:body=body.replace('rc.'+key+'[s]',f'0x{program[word][j]:08X}u')
  body=re.sub(r'\bs\b',str(j)+'u',body)
  out+='    { /* literal stage '+str(j)+' */'+body+'\n    }\n'
 for variant,final in enumerate(program['finals']):
  if len(program['finals'])>1:
   out+=('    if' if variant==0 else '    else if')+f'(rc.final0==0x{final:08X}u){{\n'
  body=tail.replace('rc.final0 || rc.final1','1').replace('uint32_t f0 = rc.final0, f1 = rc.final1, fflags = f1 & 0xFF;',f'uint32_t f0 = 0x{final:08X}u, f1 = 0x{program["final1"]:08X}u, fflags = f1 & 0xFF;')
  out+=body+'\n'
  if len(program['finals'])>1:out+='        return;\n    }\n'
 if len(program['finals'])>1:out+='    /* Only validated/matched final selectors reach this program. */\n    for(int c=0;c<4;c++)result[c]=0;\n'
 out+='}\n'
 header+=f'static const uint32_t nv_literal_{cls}_words[4][{n}]={{\n'
 for key in ['rgb_in','alpha_in','rgb_out','alpha_out']:header+='    {'+','.join(f'0x{x:08X}u' for x in program[key][:n])+'},\n'
 header+='};\n'
header+='''static unsigned nv_gpu_literal_program(const Nv2aCombiner *rc)
{
'''
for p in programs:
 cls=p['class'];n=p['control']&255
 header+=f'    if(rc->control==0x{p["control"]:08X}u && rc->stage_program==0x{p["stages"]:08X}u && rc->final1==0x{p["final1"]:08X}u && ('+' || '.join(f'rc->final0==0x{x:08X}u' for x in p['finals'])+')){\n'
 header+=f'        unsigned s;for(s=0;s<{n};s++)if(rc->color_icw[s]!=nv_literal_{cls}_words[0][s] || rc->alpha_icw[s]!=nv_literal_{cls}_words[1][s] || rc->color_ocw[s]!=nv_literal_{cls}_words[2][s] || rc->alpha_ocw[s]!=nv_literal_{cls}_words[3][s])break;\n'
 header+=f'        if(s=={n})return {cls};\n    }}\n'
header+='    return 0;\n}\nstatic void nv_gpu_literal_fixture(Nv2aCombiner *rc,unsigned program,unsigned variant)\n{\n    memset(rc,0,sizeof *rc);\n    switch(program){\n'
for p in programs:
 cls=p['class'];n=p['control']&255
 header+=f'    case {cls}:\n        rc->control=0x{p["control"]:08X}u;rc->stage_program=0x{p["stages"]:08X}u;rc->final1=0x{p["final1"]:08X}u;\n'
 header+='        {static const uint32_t finals[]={'+','.join(f'0x{x:08X}u' for x in p['finals'])+f'}};rc->final0=finals[variant%{len(p["finals"])}];}}\n'
 for key,idx in [('color_icw',0),('alpha_icw',1),('color_ocw',2),('alpha_ocw',3)]:header+=f'        memcpy(rc->{key},nv_literal_{cls}_words[{idx}],{n}*4);\n'
 header+='        break;\n'
header+='    default:break;\n    }\n}\n#endif\n';out+='#endif\n'
for name,content in [('nv2a_gpu_literal.inc',out),('nv2a_gpu_literal_programs.h',header)]:
 target=k/name
 print(f'[LITERAL-GEN] checking {name}', flush=True)
 if not target.exists() or target.read_text()!=content:
  print(f'[LITERAL-GEN] writing {name}', flush=True)
  target.write_text(content)
 print(f'[LITERAL-GEN] ready {name}', flush=True)
print('Generated 3 exact material bodies and CPU classifier')
