"""Generate scalar SSA C specializations from QPR2's extracted shader archive.

Usage: python tools/compile_qpr2_vertex_programs.py ATV.zip [output.h]
The generated header stays local; generic builds can use the fallback.
The bytecode matcher compares every instruction, including unused bits. There
are no baked-in matrices, lighting values, texture coordinates, or vertices.
"""
from pathlib import Path
import hashlib
import struct
import sys
import zipfile


def generate(archive):
    programs = {}
    with zipfile.ZipFile(archive) as z:
        for name in sorted(z.namelist()):
            if '/VertexShader/Assembled/VS' not in '/' + name:
                continue
            raw = z.read(name)
            magic, count = struct.unpack_from('<HH', raw)
            assert magic == 0x2078 and len(raw) == 4 + count * 16
            words = tuple(struct.iter_unpack('<4I', raw[4:]))
            assert 0 < count <= 136 and words[-1][3] & 1
            assert all(not (w[3] & 1) for w in words[:-1])
            programs.setdefault(words, []).append(Path(name).name)
    assert programs
    result = ['/* Generated by tools/compile_qpr2_vertex_programs.py. Do not edit.',
              ' * Archive SHA256: ' + hashlib.sha256(Path(archive).read_bytes()).hexdigest(),
              ' * Exact uploaded-word match; live constants; no context writes. */',
              '#ifndef NV2A_VSH_COMPILED_H', '#define NV2A_VSH_COMPILED_H',
              'typedef void (*NvVshNative)(const float in[16][4], Nv2aVshOutput *out);',
              'typedef struct { unsigned count, inputs, position_kind; const uint32_t (*words)[4]; NvVshNative run; } NvVshCompiled;',
              'static float nv_vsh_compiled_rcc(float x) {',
              ' float f=1.0f/x;',
              ' if(fabsf(f)<5.42101e-20f)f=f<0?-5.42101e-20f:5.42101e-20f;',
              ' if(fabsf(f)>1.884467e19f)f=f<0?-1.884467e19f:1.884467e19f;',
              ' return f;', '}',
              'static float nv_vsh_compiled_lit(float x,float y,float w) {',
              ' float nh=y>0.0f?y:0.0f;',
              ' float p=w < -127.9961f ? -127.9961f : (w>127.9961f?127.9961f:w);',
              ' return x>0.0f?powf(nh,p):0.0f;', '}']
    entries = []
    position_forms = {}
    for number, (words, names) in enumerate(programs.items()):
        lines = []
        temp = [['0.0f'] * 4 for _ in range(12)]
        pos = ['0.0f'] * 4
        regs = [['0.0f'] * 4 for _ in range(13)]
        for r in [3, 4, 9, 10, 11, 12]:
            regs[r][3] = '1.0f'
        serial = 0
        inputs = 0

        def emit(expr):
            nonlocal serial
            n = 'v' + str(serial)
            serial += 1
            lines.append(' const float ' + n + '=' + expr + ';')
            return n

        def source(w, which):
            nonlocal inputs
            if which == 0:
                neg, swz, mux, reg = w[1] >> 8 & 1, w[1] & 255, w[2] >> 26 & 3, w[2] >> 28 & 15
            elif which == 1:
                neg, swz, mux, reg = w[2] >> 25 & 1, w[2] >> 17 & 255, w[2] >> 11 & 3, w[2] >> 13 & 15
            else:
                neg, swz, mux, reg = w[2] >> 10 & 1, w[2] >> 2 & 255, w[3] >> 28 & 3, (w[2] & 3) << 2 | w[3] >> 30 & 3
            if mux == 1:
                v = pos if reg == 12 else temp[reg if reg < 12 else 0]
            elif mux == 2:
                vi = w[1] >> 9 & 15
                inputs |= 1 << vi
                v = ['in[%d][%d]' % (vi, c) for c in range(4)]
            else:
                ci = w[1] >> 13 & 255
                assert not (w[3] & 2), 'relative constant unsupported'
                ci = ci if ci < 192 else 0
                v = ['s_const[%d][%d]' % (ci, c) for c in range(4)]
            v = [v[swz >> (6 - c * 2) & 3] for c in range(4)]
            return ['(-(' + x + '))' for x in v] if neg else v[:]

        for w in words:
            mac, ilu = w[1] >> 21 & 15, w[1] >> 25 & 7
            mm, im, om = w[3] >> 24 & 15, w[3] >> 16 & 15, w[3] >> 12 & 15
            dst, oa = w[3] >> 20 & 15, w[3] >> 3 & 255
            oi = bool(w[3] & 4)
            assert not om or w[3] & 2048, 'context output unsupported'
            assert mac != 13, 'address register unsupported'
            # Snapshot both units before any register writes. Dead arithmetic
            # is left to the host compiler; finite arithmetic order is explicit.
            a = source(w, 0) if mac else ['0.0f'] * 4
            b = source(w, 1) if mac in (2, 4, 5, 6, 7, 8, 9, 10, 11, 12) else ['0.0f'] * 4
            c = source(w, 2) if ilu or mac in (3, 4) else ['0.0f'] * 4
            m = ['0.0f'] * 4
            i = ['0.0f'] * 4
            used_m = mm | (om if not oi else 0)
            used_i = im | (om if oi else 0)
            if mac in (5, 6, 7) and used_m:
                terms = [a[j] + '*' + b[j] for j in range(3)]
                if mac == 6:
                    terms.append(b[3])
                elif mac == 7:
                    terms.append(a[3] + '*' + b[3])
                m = [emit('+'.join(terms))] * 4
            else:
                for j in range(4):
                    if not used_m & (8 >> j) or not mac:
                        continue
                    x, y, z = a[j], b[j], c[j]
                    expr = {1: x, 2: x+'*'+y, 3: x+'+'+z, 4: x+'*'+y+'+'+z,
                            8: ['1.0f', a[1]+'*'+b[1], a[2], b[3]][j],
                            9: x+'<'+y+'?'+x+':'+y, 10: x+'>='+y+'?'+x+':'+y,
                            11: x+'<'+y+'?1.0f:0.0f', 12: x+'>='+y+'?1.0f:0.0f'}.get(mac)
                    assert expr is not None, mac
                    m[j] = emit(expr)
            if ilu and used_i:
                if ilu in (2, 3, 4):
                    x = c[0]
                    expr = {2: '('+x+'==0.0f?INFINITY:1.0f/('+x+'))',
                            3: 'nv_vsh_compiled_rcc('+x+')',
                            4: '1.0f/sqrtf(fabsf('+x+'))'}[ilu]
                    i = [emit(expr)] * 4
                else:
                    assert ilu in (1, 7), ilu
                    for j in range(4):
                        if not used_i & (8 >> j):
                            continue
                        expr = c[j] if ilu == 1 else ['1.0f', '('+c[0]+'>0.0f?'+c[0]+':0.0f)',
                            'nv_vsh_compiled_lit('+c[0]+','+c[1]+','+c[3]+')', '1.0f'][j]
                        i[j] = emit(expr)

            def write(target, value, mask):
                for j in range(4):
                    if mask & (8 >> j):
                        target[j] = value[j]

            if mac and (dst <= 12):
                write(pos if dst == 12 else temp[dst], m, mm)
            it = 1 if mac else dst
            if ilu and it <= 12:
                write(pos if it == 12 else temp[it], i, im)
            if om:
                if oa == 0:
                    write(pos, i if oi else m, om)
                elif oa < 13:
                    write(regs[oa], i if oi else m, om)
        # Avoid unused SSA declarations even in /W4 builds.
        outputs = [('pos', pos), ('d0', regs[3]), ('d1', regs[4]), ('fog', regs[5])]
        outputs += [('tex[%d]' % j, regs[9+j]) for j in range(4)]
        for member, value in outputs:
            for j in range(4):
                lines.append(' out->%s[%d]=%s;' % (member, j, value[j]))
        # Prove position equivalence from the generated SSA, not shader names
        # or upload addresses. Only the two fully verified forms are eligible
        # for object-space bounds and the first GPU geometry path.
        import re
        definitions = dict(re.findall(r'const float (v\d+)=(.*?);', '\n'.join(lines)))
        memo = {}
        def expand_position(x):
            if x not in memo:
                memo[x] = re.sub(r'\bv\d+\b', lambda m: '('+expand_position(m[0])+')', definitions.get(x, x))
            return memo[x]
        signature = tuple(expand_position(x) for x in pos)
        if 'VS0000' in names:
            position_forms[signature] = 1
        if 'VS1000' in names:
            position_forms[signature] = 2
        position_kind = position_forms.get(signature, 0)
        assert position_kind, 'unproven position expression: '+str(names)
        live = set()
        kept = []
        import re
        for line in reversed(lines):
            declaration = re.match(r' const float (v\d+)=', line)
            if declaration and declaration[1] not in live:
                continue
            kept.append(line)
            live.update(re.findall(r'\bv\d+\b', line.split('=', 1)[1]))
        result += ['/* ' + ', '.join(names) + ' */',
                   'static void nv_vsh_native_%d(const float in[16][4], Nv2aVshOutput *out) {' % number,
                   *reversed(kept), '}',
                   'static const uint32_t nv_vsh_words_%d[][4]={' % number]
        result += [' {' + ','.join('0x%08Xu' % x for x in w) + '},' for w in words]
        result += ['};']
        entries.append(' {%d,0x%04Xu,%d,nv_vsh_words_%d,nv_vsh_native_%d},' % (len(words), inputs, position_kind, number, number))
    result += ['static const NvVshCompiled nv_vsh_compiled[]={', *entries, '};', '#endif', '']
    return '\n'.join(result), len(programs)


if __name__ == '__main__':
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / 'third_party/xboxrecomp/src/kernel/nv2a_vsh_compiled.h'
    text, count = generate(sys.argv[1])
    output.write_text(text)
    print('Generated', count, 'exact-match specializations:', output, len(text), 'bytes')
