"""Embed compute/ROV shader sources and their shared scalar pixel kernel."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]/'third_party/xboxrecomp/src/kernel'
output='/* Generated by tools/embed_qpr2_gpu_shader.py. */\n'
for name,symbol in [('nv2a_gpu_raster.hlsl','nv_gpu_shader_source'),('nv2a_gpu_rov.hlsl','nv_gpu_rov_source'),('nv2a_gpu_report_reset.hlsl','nv_gpu_report_reset_source'),('nv2a_gpu_coverage.hlsl','nv_gpu_coverage_source'),('nv2a_gpu_clear.hlsl','nv_gpu_clear_source'),('nv2a_gpu_geometry.hlsl','nv_gpu_geometry_source'),('nv2a_gpu_texcopy.hlsl','nv_gpu_texcopy_source')]:
    source=(root/name).read_text()
    for include in ['nv2a_gpu_types.h','nv2a_gpu_pixel.inc','nv2a_gpu_literal.inc','nv2a_gpu_compact.inc','nv2a_gpu_shade.inc','nv2a_gpu_source.inc','nv2a_gpu_raw_types.h','nv2a_gpu_vsh.inc','nv2a_gpu_prepare.inc']:
        source=source.replace('#include "'+include+'"',(root/include).read_text())
    output+='static const char '+symbol+'[] =\n'
    if len(source.encode())>60000:
        data=source.encode();output+='{\n'
        for offset in range(0,len(data),32):output+=','.join('0x%02x'%b for b in data[offset:offset+32])+',\n'
        output+='0x00};\n'
    else:output+='\n'.join(json.dumps(line+'\n') for line in source.splitlines())+';\n'
    print('Embedded',name,len(source.encode()),'bytes')
(root/'nv2a_gpu_shader.h').write_text(output)
